`timescale 1ns/1ps

// 字库独立验证：用“整字符 35 位打包 + 移位”的期望表逐字符、逐行比对，
// 与 DUT 的逐行 case 实现互为独立表示，可发现行序、位序和缺行错误。
module tb_osd_font;

    reg  [6:0] ch;
    reg  [2:0] row;
    wire [4:0] glyph;

    integer fails;
    integer checks;
    integer ci;
    integer r;
    reg [34:0] exp;
    reg [4:0]  exp_row;

    osd_font_rom dut (
        .ch    (ch),
        .row   (row),
        .glyph (glyph)
    );

    function [34:0] exp_glyph;
        input [6:0] c;
        begin
            case (c)
                // 数字
                7'h30: exp_glyph = {5'b01110,5'b10001,5'b10011,5'b10101,5'b11001,5'b10001,5'b01110};
                7'h31: exp_glyph = {5'b00100,5'b01100,5'b00100,5'b00100,5'b00100,5'b00100,5'b01110};
                7'h32: exp_glyph = {5'b01110,5'b10001,5'b00001,5'b00010,5'b00100,5'b01000,5'b11111};
                7'h33: exp_glyph = {5'b11111,5'b00010,5'b00100,5'b00010,5'b00001,5'b10001,5'b01110};
                7'h34: exp_glyph = {5'b00010,5'b00110,5'b01010,5'b10010,5'b11111,5'b00010,5'b00010};
                7'h35: exp_glyph = {5'b11111,5'b10000,5'b11110,5'b00001,5'b00001,5'b10001,5'b01110};
                7'h36: exp_glyph = {5'b00110,5'b01000,5'b10000,5'b11110,5'b10001,5'b10001,5'b01110};
                7'h37: exp_glyph = {5'b11111,5'b00001,5'b00010,5'b00100,5'b01000,5'b01000,5'b01000};
                7'h38: exp_glyph = {5'b01110,5'b10001,5'b10001,5'b01110,5'b10001,5'b10001,5'b01110};
                7'h39: exp_glyph = {5'b01110,5'b10001,5'b10001,5'b01111,5'b00001,5'b00010,5'b01100};
                // 大写字母
                7'h41: exp_glyph = {5'b01110,5'b10001,5'b10001,5'b11111,5'b10001,5'b10001,5'b10001};
                7'h42: exp_glyph = {5'b11110,5'b10001,5'b10001,5'b11110,5'b10001,5'b10001,5'b11110};
                7'h43: exp_glyph = {5'b01110,5'b10001,5'b10000,5'b10000,5'b10000,5'b10001,5'b01110};
                7'h44: exp_glyph = {5'b11110,5'b10001,5'b10001,5'b10001,5'b10001,5'b10001,5'b11110};
                7'h45: exp_glyph = {5'b11111,5'b10000,5'b10000,5'b11110,5'b10000,5'b10000,5'b11111};
                7'h46: exp_glyph = {5'b11111,5'b10000,5'b10000,5'b11110,5'b10000,5'b10000,5'b10000};
                7'h47: exp_glyph = {5'b01110,5'b10001,5'b10000,5'b10111,5'b10001,5'b10001,5'b01110};
                7'h48: exp_glyph = {5'b10001,5'b10001,5'b10001,5'b11111,5'b10001,5'b10001,5'b10001};
                7'h49: exp_glyph = {5'b01110,5'b00100,5'b00100,5'b00100,5'b00100,5'b00100,5'b01110};
                7'h4a: exp_glyph = {5'b00111,5'b00010,5'b00010,5'b00010,5'b00010,5'b10010,5'b01100};
                7'h4b: exp_glyph = {5'b10001,5'b10010,5'b10100,5'b11000,5'b10100,5'b10010,5'b10001};
                7'h4c: exp_glyph = {5'b10000,5'b10000,5'b10000,5'b10000,5'b10000,5'b10000,5'b11111};
                7'h4d: exp_glyph = {5'b10001,5'b11011,5'b10101,5'b10101,5'b10001,5'b10001,5'b10001};
                7'h4e: exp_glyph = {5'b10001,5'b11001,5'b10101,5'b10011,5'b10001,5'b10001,5'b10001};
                7'h4f: exp_glyph = {5'b01110,5'b10001,5'b10001,5'b10001,5'b10001,5'b10001,5'b01110};
                7'h50: exp_glyph = {5'b11110,5'b10001,5'b10001,5'b11110,5'b10000,5'b10000,5'b10000};
                7'h51: exp_glyph = {5'b01110,5'b10001,5'b10001,5'b10001,5'b10101,5'b10010,5'b01101};
                7'h52: exp_glyph = {5'b11110,5'b10001,5'b10001,5'b11110,5'b10100,5'b10010,5'b10001};
                7'h53: exp_glyph = {5'b01111,5'b10000,5'b10000,5'b01110,5'b00001,5'b00001,5'b11110};
                7'h54: exp_glyph = {5'b11111,5'b00100,5'b00100,5'b00100,5'b00100,5'b00100,5'b00100};
                7'h55: exp_glyph = {5'b10001,5'b10001,5'b10001,5'b10001,5'b10001,5'b10001,5'b01110};
                7'h56: exp_glyph = {5'b10001,5'b10001,5'b10001,5'b10001,5'b10001,5'b01010,5'b00100};
                7'h57: exp_glyph = {5'b10001,5'b10001,5'b10001,5'b10101,5'b10101,5'b11011,5'b10001};
                7'h58: exp_glyph = {5'b10001,5'b10001,5'b01010,5'b00100,5'b01010,5'b10001,5'b10001};
                7'h59: exp_glyph = {5'b10001,5'b10001,5'b01010,5'b00100,5'b00100,5'b00100,5'b00100};
                7'h5a: exp_glyph = {5'b11111,5'b00001,5'b00010,5'b00100,5'b01000,5'b10000,5'b11111};
                // 标点
                7'h2d: exp_glyph = {5'b00000,5'b00000,5'b00000,5'b01110,5'b00000,5'b00000,5'b00000};
                7'h2e: exp_glyph = {5'b00000,5'b00000,5'b00000,5'b00000,5'b00000,5'b01100,5'b01100};
                7'h3a: exp_glyph = {5'b00000,5'b01100,5'b01100,5'b00000,5'b01100,5'b01100,5'b00000};
                7'h2f: exp_glyph = {5'b00001,5'b00010,5'b00010,5'b00100,5'b01000,5'b01000,5'b10000};
                default: exp_glyph = 35'd0;
            endcase
        end
    endfunction

    initial begin
        fails  = 0;
        checks = 0;

        // 遍历全部 ASCII：受支持字符比对字模，其余必须输出 0。
        for (ci = 0; ci < 128; ci = ci + 1) begin
            ch  = ci[6:0];
            exp = exp_glyph(ch);
            for (r = 0; r < 8; r = r + 1) begin
                row = r[2:0];
                #1;
                if (r < 7)
                    exp_row = (exp >> (5 * (6 - r))) & 5'h1F;
                else
                    exp_row = 5'h00;
                checks = checks + 1;
                if (glyph !== exp_row) begin
                    fails = fails + 1;
                    if (fails <= 12)
                        $display("FAIL font ch=0x%02h row=%0d got=%b exp=%b",
                                 ch, r, glyph, exp_row);
                end
            end
        end

        if (fails == 0) begin
            $display("PASS osd_font: %0d row checks across 128 ASCII codes", checks);
            $finish;
        end else begin
            $display("FAIL osd_font: %0d/%0d row checks failed", fails, checks);
            $fatal(1);
        end
    end

endmodule
